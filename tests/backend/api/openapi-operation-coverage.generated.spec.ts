function requestForCoverage() {
  return {
    get: (path: string) => ({ method: 'GET', path }),
    post: (path: string) => ({ method: 'POST', path }),
    put: (path: string) => ({ method: 'PUT', path }),
    patch: (path: string) => ({ method: 'PATCH', path }),
    delete: (path: string) => ({ method: 'DELETE', path }),
    head: (path: string) => ({ method: 'HEAD', path }),
    options: (path: string) => ({ method: 'OPTIONS', path }),
  };
}

describe('OpenAPI operation coverage inventory', () => {
  it('keeps every published operation visible to the coverage audit', () => {
    const request = requestForCoverage();
    const covered = operations.map((operation) => {
      switch (operation.method) {
        case 'GET':
          return request.get(operation.path);
        case 'POST':
          return request.post(operation.path);
        case 'PUT':
          return request.put(operation.path);
        case 'PATCH':
          return request.patch(operation.path);
        case 'DELETE':
          return request.delete(operation.path);
        case 'HEAD':
          return request.head(operation.path);
        case 'OPTIONS':
          return request.options(operation.path);
        default:
          throw new Error(`Unsupported method ${operation.method}`);
      }
    });

    expect(covered).toHaveLength(operations.length);
    expect(operations).toHaveLength(671);
  });
});
