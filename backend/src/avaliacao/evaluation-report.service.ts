import { Injectable, NotFoundException } from '@nestjs/common';
import { QueryResultRow } from 'pg';

import { GenerateAvaliacaoReportDto } from './avaliacao.dto';
import { AvaliacaoDataAccessService } from './avaliacao-data-access.service';
import { ReportRequestRow } from './avaliacao.types';

@Injectable()
export class EvaluationReportService {
  constructor(private readonly data: AvaliacaoDataAccessService) {}

  async requestEvaluationSheet(
    evaluationId: string,
    input: GenerateAvaliacaoReportDto,
  ) {
    this.data.ensureDatabase();
    const exists = await this.data.query<QueryResultRow>(
      `SELECT 1 FROM hr.performance_evaluation WHERE id = $1::uuid`,
      [evaluationId],
    );
    if (!exists[0]) {
      throw new NotFoundException('Performance evaluation not found');
    }
    return this.createReportRequest(
      'AVALIACAO_FICHA_DESEMPENHO',
      'Ficha de avaliacao de desempenho',
      {
        evaluationId,
        format: input.formato ?? 'PDF',
      },
    );
  }

  async requestCycleReport(
    periodLabel: string,
    input: GenerateAvaliacaoReportDto,
  ) {
    this.data.ensureDatabase();
    return this.createReportRequest(
      'AVALIACAO_RELATORIO_CICLO',
      'Relatorio de ciclo de avaliacao',
      {
        periodLabel,
        workLocationId: input.lotacaoId ?? null,
        format: input.formato ?? 'PDF',
      },
    );
  }

  private async createReportRequest(
    code: string,
    name: string,
    parameters: Record<string, unknown>,
  ) {
    const definitionId = await this.ensureDefinition(
      code,
      name,
      `GENERATE request generated by avaliacao runtime for ${code}`,
    );
    const rows = await this.data.query<ReportRequestRow>(
      `
      INSERT INTO public.report_request (
        definition_id,
        status,
        parameters
      )
      VALUES (
        $1::uuid,
        'REQUESTED'::"ReportRequestStatus",
        $2::jsonb
      )
      RETURNING id, status::text AS status, requested_at
      `,
      [definitionId, JSON.stringify(parameters)],
    );
    return {
      id: rows[0]?.id ?? '',
      status: rows[0]?.status ?? 'REQUESTED',
      requestedAt: this.data.toIso(rows[0]?.requested_at ?? new Date()),
    };
  }

  private async ensureDefinition(
    code: string,
    name: string,
    description: string,
  ): Promise<string> {
    const rows = await this.data.query<{ id: string } & QueryResultRow>(
      `
      WITH inserted AS (
        INSERT INTO public.report_definition (
          tenant_id,
          code,
          name,
          description,
          module_key,
          status
        )
        SELECT
          public.sgp_current_tenant_uuid(),
          $1,
          $2,
          $3,
          'avaliacao',
          'ACTIVE'::"RecordStatus"
        WHERE NOT EXISTS (
          SELECT 1
          FROM public.report_definition
          WHERE code = $1
            AND tenant_id = public.sgp_current_tenant_uuid()
        )
        RETURNING id::text
      )
      SELECT id::text FROM inserted
      UNION ALL
      SELECT id::text
      FROM public.report_definition
      WHERE code = $1
        AND tenant_id = public.sgp_current_tenant_uuid()
      LIMIT 1
      `,
      [code, name, description],
    );
    return rows[0]?.id ?? '';
  }
}
