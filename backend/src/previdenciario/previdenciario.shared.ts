export function ensureDatabase(databaseService: DatabaseService): void {
  if (!databaseService.configured) {
    throw new ServiceUnavailableException('DATABASE_URL is not configured');
  }
}

export async function employeeRow(
  databaseService: DatabaseService,
  id: string,
): Promise<EmployeeRetirementRow> {
  const rows = await databaseService.query<EmployeeRetirementRow>(
    `
    SELECT id, registration, name, birth_date, hired_on, cpf
    FROM hr.employee
    WHERE id = $1::uuid
    `,
    [id],
  );
  if (!rows[0]) {
    throw new NotFoundException('Employee not found');
  }
  return rows[0];
}

