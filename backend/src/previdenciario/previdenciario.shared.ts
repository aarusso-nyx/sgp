export async function createReportRequest(
  databaseService: DatabaseService,
  code: string,
  name: string,
  parameters: Record<string, unknown>,
) {
  const definitionId = await ensureDefinition(
    databaseService,
    code,
    name,
    `GENERATE request generated by previdenciario runtime for ${code}`,
  );
  const rows = await databaseService.query<ReportRequestRow>(
    `
    INSERT INTO public.report_request (
      definition_id,
      status,
      parameters
    )
    VALUES (
      $1::uuid,
      'REQUESTED'::"ReportRequestStatus",
      $2::jsonb
    )
    RETURNING id, status::text AS status, requested_at
    `,
    [definitionId, JSON.stringify(parameters)],
  );
  return {
    id: rows[0]?.id ?? '',
    status: rows[0]?.status ?? 'REQUESTED',
    requestedAt: toIso(rows[0]?.requested_at ?? new Date()),
  };
}

async function ensureDefinition(
  databaseService: DatabaseService,
  code: string,
  name: string,
  description: string,
): Promise<string> {
  const rows = await databaseService.query<{ id: string } & QueryResultRow>(
    `
    WITH inserted AS (
      INSERT INTO public.report_definition (
        tenant_id,
        code,
        name,
        description,
        module_key,
        status
      )
      SELECT
        public.sgp_current_tenant_uuid(),
        $1,
        $2,
        $3,
        'previdenciario',
        'ACTIVE'::"RecordStatus"
      WHERE NOT EXISTS (
        SELECT 1
        FROM public.report_definition
        WHERE code = $1
          AND tenant_id = public.sgp_current_tenant_uuid()
      )
      RETURNING id::text
    )
    SELECT id::text FROM inserted
    UNION ALL
    SELECT id::text
    FROM public.report_definition
    WHERE code = $1
      AND tenant_id = public.sgp_current_tenant_uuid()
    LIMIT 1
    `,
    [code, name, description],
  );
  return rows[0]?.id ?? '';
}

